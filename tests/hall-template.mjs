import assert from 'node:assert/strict';
import {expandLayout,parseNumbers} from '../tools/hall-model.mjs';
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const d={id:'test-hall',name:'テスト「店舗」<&',prefecture:'大阪府',city:'堺市',minrepo_url:'https://min-repo.com/tag/test/',layout_date:'2026-09-20',rows:[{numbers:[101,103,104],x:100,y:100,direction:'right'},{numbers:[110,109],x:100,y:200,direction:'down'}]};
assert.deepEqual(parseNumbers('１０１-１０３,110-108'),[101,102,103,110,109,108]);
assert.deepEqual(expandLayout(d).positions[109],[100,248,44,44]);
const v2={version:2,id:'v2-hall',name:'V2店舗',prefecture:'大阪府',city:'堺市',minrepo_url:'https://min-repo.com/tag/v2/',layout_date:'2026-09-20',width:800,height:600,islands:[{name:'島1',shape:'line',x:100,y:100,count:3,size:24,pitch:30,angle:0,radius:100,sweep:90,confirmed:true,numbers:[201,202,203],machine:'確認用'}]};
assert.deepEqual(expandLayout(v2).positions[203],[160,100,24,24]);
assert.throws(()=>expandLayout({...v2,islands:[{...v2.islands[0],confirmed:false}]}),/確認待ち/);
assert.throws(()=>expandLayout({...d,id:'../escape'}));
assert.throws(()=>expandLayout({...d,rows:[...d.rows,d.rows[0]]}),/重複/);
assert.throws(()=>expandLayout({...d,rows:[d.rows[0],{...d.rows[0],numbers:[201]}]}),/重な/);
assert.throws(()=>expandLayout({...d,minrepo_url:'https://min-repo.com.evil.example/tag/test/'}));
assert.throws(()=>expandLayout({...d,rows:[{numbers:[1,2],x:0,y:0,direction:'left'}]}),/範囲外/);
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'floor777-template-')),input=path.join(tmp,'input.json'),out=path.join(tmp,'output');
fs.writeFileSync(input,JSON.stringify(d));
execFileSync(process.execPath,['tools/build-hall.mjs',input,'--out',out]);
const html=fs.readFileSync(path.join(out,'halls/test-hall/index.html'),'utf8');
assert(!html.includes('hyper-arrow-mihara'));assert(!html.includes('HYPER ARROW'));assert(html.includes('テスト「店舗」&lt;&amp;'));assert(html.includes('noindex'));
assert.equal(JSON.parse(fs.readFileSync(path.join(out,'registration.json'))).status,'draft');
assert.equal(JSON.parse(fs.readFileSync(path.join(out,'data/test-hall.json'))).seat_count,5);
assert.throws(()=>execFileSync(process.execPath,['tools/build-hall.mjs',input,'--out',out],{stdio:'pipe'}));
console.log('PASS: ranges, missing numbers, duplicates, overlap, invalid URL/path, generation and overwrite protection');
